export const parseFormatDimensions = (format?: string, fallbackW = 2800, fallbackH = 2070): { width: number; height: number } => {
  if (!format) return { width: fallbackW, height: fallbackH };
  const parts = String(format)
    .toLowerCase()
    .replace(/[×*х]/g, "x")
    .split("x")
    .map((n) => parseInt(n.trim(), 10));
  if (parts.length >= 2 && parts[0] > 100 && parts[1] > 100) {
    return { width: parts[0], height: parts[1] };
  }
  return { width: fallbackW, height: fallbackH };
};
